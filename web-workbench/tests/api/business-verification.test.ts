import {test} from 'node:test';
import assert from 'node:assert/strict';
import {UserContextResolver} from '../../apps/server/src/user-context.ts';
import {BusinessVerificationBridge,MockLogProvider,type BusinessProvider} from '../../apps/server/src/business-verification.ts';
const binding=(owner:string,id=owner)=>({ownerId:owner,id,serviceIdentity:'service-'+owner,scenario:'log-inspection',directory:'/isolated/'+owner});
test('T4/T5: A/B/C phones and tokens stay scoped; correct, wrong, replay, expiry and cancel',async()=>{
  let now=1000;
  const phones:string[]=[];
  const resolver=new UserContextResolver(async owner=>({id:owner,name:owner,phone:'+861380000000'+['A','B','C'].indexOf(owner),status:'ACTIVE'}));
  const mock=new MockLogProvider(()=>now),provider:BusinessProvider={send:async phone=>{phones.push(phone);return mock.send(phone);},verify:(id,code)=>mock.verify(id,code),query:(token,q)=>mock.query(token,q)};
  const bridge=new BusinessVerificationBridge(resolver,provider,()=>now);
  const scopes=await Promise.all(['A','B','C'].map(owner=>resolver.bind(owner,binding(owner),'mock-logs')));
  assert.throws(()=>resolver.public({context:'trusted-business-call'}),/UNTRUSTED_TOOL_CONTEXT/);
  await assert.rejects(resolver.bind('A',binding('B'),'mock-logs'),/FORBIDDEN/);
  const challenges=await Promise.all(scopes.map(scope=>bridge.send(scope)));
  assert.deepEqual(phones,['+8613800000000','+8613800000001','+8613800000002']);
  assert.equal(resolver.public(scopes[0]).maskedPhone,'****0000');
  assert.equal('phone' in resolver.public(scopes[0]),false);
  const ids=challenges.map(c=>'challengeId'in c?c.challengeId!:'');
  await assert.rejects(bridge.submit(scopes[1],ids[0],'123456'),/NOT_FOUND/);
  assert.equal((await bridge.submit(scopes[0],ids[0],'000000')).verified,false);
  assert.equal((await bridge.submit(scopes[0],ids[0],'123456')).verified,true);
  assert.equal(bridge.status(scopes[0]).state,'AUTHORIZED');
  await assert.rejects(bridge.submit(scopes[0],ids[0],'123456'),/CLOSED/);
  assert.equal((await bridge.query(scopes[0],'trace A') as {source:string}).source,'mock-logs');
  await assert.rejects(bridge.query(scopes[1],'trace A'),/VERIFICATION_REQUIRED/);
  bridge.cancel(scopes[1],ids[1]);await assert.rejects(bridge.submit(scopes[1],ids[1],'123456'),/CLOSED/);
  now+=120001;assert.equal(bridge.status(scopes[2]).state,'EXPIRED');await assert.rejects(bridge.submit(scopes[2],ids[2],'123456'),/CLOSED/);
  const transcript=JSON.stringify(challenges)+JSON.stringify(scopes.map(scope=>bridge.status(scope)));
  assert.equal(transcript.includes('123456'),false);assert.equal(transcript.includes('token'),false);assert.equal(transcript.includes('+86138'),false);
});
test('T5: cancellation during target verification cannot authorize; concurrent/repeated submits rejected',async()=>{
  const resolver=new UserContextResolver(async id=>({id,name:id,phone:'+8613800000000',status:'ACTIVE'}));
  const scope=await resolver.bind('A',binding('A'),'mock-logs');
  let finish!:(value:{token:string;expires:number})=>void;
  const bridge=new BusinessVerificationBridge(resolver,{send:async()=>({id:'remote',expires:100000}),verify:async()=>new Promise(resolve=>{finish=resolve;}),query:async()=>({})},()=>1000);
  const challenge=await bridge.send(scope),id='challengeId'in challenge?challenge.challengeId!:'';
  const pending=bridge.submit(scope,id,'123456');
  await assert.rejects(bridge.submit(scope,id,'123456'),/CLOSED/);
  bridge.cancel(scope,id);finish({token:'secret-target-token',expires:99999});
  await assert.rejects(pending,/CLOSED/);await assert.rejects(bridge.query(scope,'query'),/VERIFICATION_REQUIRED/);
});
